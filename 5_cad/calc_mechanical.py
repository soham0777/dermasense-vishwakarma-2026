"""
Mechanical calculations for the strip contact clamp and bench rig (v0.1). Writes calc_mechanical_report.md.
Labels: [DS] supplier/datasheet value (verify on the part you buy) · [EST] estimate · [DES] design choice.
The CAD build (sw_build.py) imports the dimension values from DIMS so drawings and calculations agree.
"""
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
GEO = json.loads((HERE.parent / "4_sensor_strip" / "strip_v0_1_geometry.json").read_text())

DIMS = dict(              # mm unless noted
    pin_d=1.02, pin_len=15.8, pin_travel=2.0, pin_force_N=0.98,   # P75-B1 per Probots listing: 100 g, 2 mm travel [DS]
    pin_hole_d=1.10,                                               # glue-in clearance for FDM [DES]
    pin_protrusion=1.60,                                           # tip above base top before clamping [DES]
    film_t=GEO["thickness_film_mm"],
    base_h=16.0, channel_h=4.0, margin_x=4.0, margin_y=7.5,        # clamp base block [DES]
    lid_t=4.0,
    dowel_d=2.0, dowel_len=12.0, dowel_hole_base=2.0, dowel_hole_lid=2.3,  # ISO 8734 2 m6 x 12 [DES]
    screw_clear=3.4, nut_af=5.7, nut_depth=2.6,                    # M3 [DES]
    dressing_t=4.0, rig_t=5.0,                                     # foam dressing thickness [EST], base acrylic [DES]
    E_petg_MPa=2000.0, kapton_tensile_MPa=231.0,                   # [DS] PETG typ. 1.8-2.2 GPa; DuPont Kapton HN
)


def main():
    d = DIMS
    k = d["pin_force_N"] / d["pin_travel"]                 # N/mm, linear spring assumption [EST]
    comp = d["pin_protrusion"] - d["film_t"]               # compression when the lid closes
    f_pin = k * comp
    f_tot = 4 * f_pin
    y_lo, y_hi = GEO["paddle_y"]
    span = (y_hi + d["margin_y"] / 2) - (y_lo - d["margin_y"] / 2)     # between the two M3 screws
    b = GEO["pads"]["SENSE_C"]["x"] + GEO["pads"]["SENSE_C"]["w"] / 2 + 8 + d["margin_x"]  # lid width along x
    inertia = b * d["lid_t"] ** 3 / 12
    defl = f_tot * span ** 3 / (48 * d["E_petg_MPa"] * inertia)
    pad_half_y = GEO["pads"]["SENSE_C"]["h"] / 2
    allow = pad_half_y - 0.15                              # keep a 0.3 mm tip fully on the pad
    tol = {"laser pad-to-hole position (same job)": 0.10, "strip hole kerf/clearance on dowel": 0.10,
           "FDM hole position": 0.20, "pin in 1.10 mm hole": 0.04, "dowel fit": 0.05}
    worst, rss = sum(tol.values()), math.sqrt(sum(v * v for v in tol.values()))
    strain = d["film_t"] / (2 * 10.0) * 100
    pull = 10.0                                            # N accidental tug on the tail [EST]
    bearing = pull / (2 * d["dowel_d"] * d["film_t"])
    tip_r = 0.10
    contact = f_pin / (math.pi * tip_r ** 2)
    rows = [
        ("Pin spring rate (linear assumption)", f"{k:.2f} N/mm", "[DS] 100 g at 2 mm travel (Probots P75-B1 listing)"),
        ("Pin compression when clamped", f"{comp:.2f} mm (of {d['pin_travel']} mm travel)", "[DES] protrusion − film"),
        ("Contact force per pin / total", f"{f_pin:.2f} N / {f_tot:.2f} N", "[EST]"),
        (f"Lid deflection (PETG, {d['lid_t']} mm, span {span:.1f} mm)", f"{defl*1000:.1f} µm", "[EST] simply supported, centre load"),
        ("Pin landing tolerance on 3 mm pad", f"allow ±{allow:.2f} mm; worst-case {worst:.2f}, RSS {rss:.2f} mm",
         f"[EST] margin {allow/worst:.1f}× worst-case"),
        ("Strip bending strain at 10 mm radius", f"{strain:.2f} %", "t/2R; Kapton yields near 3 % [DS]; LIG cracking limit unknown → T-MECH-01"),
        (f"Kapton bearing stress at dowels, {pull:.0f} N tug", f"{bearing:.0f} MPa vs {d['kapton_tensile_MPa']:.0f} MPa tensile",
         "[EST] dowels take the load, not the pins (strain relief)"),
        ("Pointed-tip contact stress (0.1 mm tip radius)", f"{contact:.0f} MPa", "[EST] may dent porous LIG → prefer rounded-head pins; verify in T-CON-01"),
        ("Stack heights", f"base {d['base_h']} mm; dressing {d['dressing_t']} mm; spacer {d['base_h']-d['dressing_t']:.0f} mm",
         "[DES] keeps the dressing top level with the clamp top"),
    ]
    lines = ["# Mechanical calculations (generated by calc_mechanical.py, 2026-10-14)", "",
             "| Quantity | Result | Basis |", "|---|---|---|"] + [f"| {a} | {b_} | {c} |" for a, b_, c in rows]
    lines += ["", "**Conclusions:**",
              f"- The two M3 screws easily provide the {f_tot:.1f} N pin reaction.",
              f"- The lid deflects only about {defl*1000:.0f} µm against {comp:.2f} mm of pin compression, so contact force is set by the pin springs, not the lid.",
              f"- The tolerance stack uses at most {worst:.2f} mm of the {allow:.2f} mm allowed.",
              "- The dowels take any pull on the strip (strain relief).",
              "- **Open risk:** pointed pin tips on porous LIG. Use rounded-head pins or a silver-paint pad, and verify in T-CON-01."]
    (HERE / "calc_mechanical_report.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[2:]))


if __name__ == "__main__":
    main()

"""
Tests for analyze_e2.py on SYNTHETIC data with known answers (written to a temporary folder, never to e2/).
The synthetic numbers are invented to exercise the maths and the decision rules; they are not predictions.
Run: python -m pytest test_analyze_e2.py -q     (or: python test_analyze_e2.py)
"""
import csv
import json
import random
import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import analyze_e2 as an  # noqa: E402
import make_e2_sheets as ms  # noqa: E402

RS_COND = {"RED": 150.0, "YELLOW": 45.0, "CYAN": 90.0, "BLUE": 40.0}
RS_REF = {"D1-C1-GREEN": 58.0, "D1-C1-MAGENTA": 61.0, "D1-C2-GREEN": 60.0, "D1-C2-MAGENTA": 62.0,
          "D2-C1-GREEN": 57.0, "D2-C1-MAGENTA": 63.0, "D2-C2-GREEN": 59.0, "D2-C2-MAGENTA": 60.0}
R0, GROWTH = 40.0, 0.12


def write_templates(d):
    for name, (header, rows) in ms.tables().items():
        with open(d / name, "w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(header)
            w.writerows(rows)


def fill(d, name, fn):
    with open(d / name, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
        header = list(rows[0].keys())
    for r in rows:
        fn(r)
    with open(d / name, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, header)
        w.writeheader()
        w.writerows(rows)


def rs_of(cell):
    key = cell.replace("E2-A-", "")
    return RS_REF.get(key, RS_COND.get(key.split("-")[-1]))


def make_synthetic(d):
    rnd = random.Random(1)
    write_templates(d)
    (d / "SYNTHETIC_DATA.txt").write_text("Synthetic test data generated by test_analyze_e2.py. NOT measurements.\n")

    def res(r):
        sid = r["sample_id"]
        if sid.startswith("E2-A-"):
            cell, L = sid[:-4], float(r["drawn_length_mm"])
            r["R_ohm"] = f"{(rs_of(cell) * L / (2.0 + GROWTH) + R0) * (1 + rnd.uniform(-0.005, 0.005)):.2f}"
        else:
            w = float(r["drawn_width_mm"])
            if sid.endswith("D1-C1-W030"):
                r["display_if_not_number"] = "OL"                     # broken narrow line
                return
            rs = 72.0 if w == 0.5 else 110.0 if w == 0.3 else 60.0
            r["R_ohm"] = f"{rs * 16 / (w + GROWTH) + R0:.2f}"

    def lw(r):
        r["measured_mm"] = f"{float(r['drawn_mm']) + (GROWTH if r['feature'] == 'line' else -GROWTH if r['feature'] == 'gap' else 0.07):.3f}"

    def vis(r):
        sid = r["sample_id"]
        bad = sid.endswith("-RED") or sid.endswith("D1-C1-W030")
        r["grade_0to5"] = "2" if bad else "3"
        r["burn_through_YN"] = "N"
        if sid.startswith("E2-A-"):
            r["tape_test_pass_fail"] = "fail" if bad else "pass"

    def iso(r):
        g = float(r["drawn_gap_mm"])
        if g < 0.5:
            r["R_ohm"], r["bridge_seen_YN"] = "20000", "Y" if g == 0.2 else "N"
        elif g == 0.8 and r["reading_no"] == "1":
            r["R_ohm"], r["bridge_seen_YN"] = "5000000", "N"
        else:
            r["display_if_not_number"], r["meter_range_ohm"], r["bridge_seen_YN"] = "OL", "40000000", "N"

    def holes(r):
        r["cut_through_YN"], r["dowel_fit_slides_tight_no"] = "Y", "slides"

    def thick(r):
        r["thickness_mm"] = "0.125" if r["location_bare_film_or_lig_pad"] == "bare_film" else "0.150"

    fill(d, "e2_resistance.csv", res)
    fill(d, "e2_linewidth.csv", lw)
    fill(d, "e2_visual.csv", vis)
    fill(d, "e2_isolation.csv", iso)
    fill(d, "e2_holes.csv", holes)
    fill(d, "e2_thickness.csv", thick)


def test_synthetic_recovers_known_values():
    d = Path(tempfile.mkdtemp(prefix="e2_synth_"))
    try:
        make_synthetic(d)
        out = an.analyse(d)
        an.write(out, d)
        rs = out["sheet_resistance_ohm_sq"]
        assert abs(rs["median"] - 60.0) / 60.0 < 0.03, rs
        assert rs["n"] == 8 and rs["verdict"] == "reproducible"
        assert abs(out["contact_R0_ohm"] - R0) < 2.0
        assert out["process_window"]["RED"].startswith("0/4")
        assert all(v.endswith("IN WINDOW") for k, v in out["process_window"].items() if k != "RED")
        assert abs(out["line_growth_mm"] - GROWTH) < 0.005
        assert out["min_reliable_line_mm"] == 0.5          # 0.3 mm line broke on one coupon and its Rs is off
        assert out["min_isolating_gap_mm"] == 0.5          # 0.2/0.3 bridged; 0.8 had one 5 Mohm reading (> 3 Mohm)
        assert abs(out["cut_hole_d_mm"] - 2.07) < 0.001
        assert abs(out["lig_relief_mm"] - 0.025) < 1e-9
        assert all(out["strip_v0_1_checks"].values()), out["strip_v0_1_checks"]
        assert abs(out["predicted_lead_R_ohm"] - rs["median"] * 85 / 1.12) < 1e-6
        saved = json.loads((d / "measured_process.json").read_text())
        assert saved["synthetic"] is True and saved["status"].startswith("SYNTHETIC")
        assert "SYNTHETIC" in (d / "e2_summary.md").read_text()
        assert (d / "e2_plots.png").exists()
    finally:
        shutil.rmtree(d, ignore_errors=True)


def test_empty_templates_give_no_data_and_no_json():
    d = Path(tempfile.mkdtemp(prefix="e2_empty_"))
    try:
        write_templates(d)
        out = an.analyse(d)
        an.write(out, d)
        assert out["status"] == "NO DATA"
        assert not (d / "measured_process.json").exists()
    finally:
        shutil.rmtree(d, ignore_errors=True)


def test_real_folder_has_no_invented_results():
    out = an.analyse(HERE)
    if out["status"] == "NO DATA":
        assert not (HERE / "measured_process.json").exists()
    assert not (HERE / "SYNTHETIC_DATA.txt").exists()


if __name__ == "__main__":
    for t in (test_synthetic_recovers_known_values, test_empty_templates_give_no_data_and_no_json,
              test_real_folder_has_no_invented_results):
        t()
        print("PASS", t.__name__)

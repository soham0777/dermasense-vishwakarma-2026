"""
Engineering calculations for the zone readout (bench reader v0.1).

Circuit per zone (see 05_electronics/kicad):  GPIO_Z -Rp- [zone: LIG electrodes + fluid] -Rp- N -Rref- GPIO_COM
ADS1115 measures V(N) to ground. Phase +: GPIO_Z=Vdd, GPIO_COM=0.  Phase -: GPIO_Z=0, GPIO_COM=Vdd.
    phase +:  V_N = Vdd * Rref / (Rref + Rx)      ->  Rx = Rref * (Vdd / V_N - 1)
    phase -:  V_N = Vdd * Rx   / (Rref + Rx)      ->  Rx = Rref * V_N / (Vdd - V_N)
    Rx = R_zone + R_leads + 2*Rp

Every input is labelled: [DS] datasheet value (verify), [PUB] published, [EST] engineering estimate,
[DES] design choice. Outputs: calc_readout_report.md, calc_readout.png. Rerun when measured values exist.
"""
import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent

VDD = 3.3                 # V, ESP32-C3 3V3 rail [DES]
RREF = 100e3              # ohm, 0.1 % [DES]
RREF_TOL = 0.001          # [DES]
RP = 1e3                  # ohm per protection resistor [DES]
FSR = [6.144, 4.096, 2.048, 1.024, 0.512, 0.256]   # ADS1115 PGA ranges, V [DS]
GAIN_ERR = 0.0015         # ADS1115 max gain error (verify in datasheet) [DS]
ADC_ZIN = 6e6             # ohm, ADS1115 input impedance order (verify for chosen PGA) [DS]
T_PHASE = 5e-3            # s per drive phase [DES]

# wet-zone geometry and fluid [DES]/[EST]
GAP = 1.0e-3              # m electrode gap (v0.1, conservative until E2) [DES]
LEN = 6.0e-3              # m electrode overlap length per zone [DES]
AREA_CM2 = 0.6 * 0.1      # cm2 exposed electrode area per electrode (6 mm x 1 mm) [DES]
KAPPA_SOLA = 1.43 + 0.06  # S/m, Solution A: 142 mM NaCl (molar cond. ~0.0101 S m2/mol) + 2.5 mM CaCl2 [EST]
KAPPA_EFF = (0.3, 1.0)    # S/m, effective conductivity of fluid inside dressing fibres (porosity/tortuosity) [EST]
T_WET = (0.2e-3, 1.0e-3)  # m, thickness of the wet layer contacting the electrodes [EST]
RS = (20.0, 100.0)        # ohm/sq, LIG sheet resistance window (literature 15-35; ours unknown) [PUB/EST]
LEAD_SQUARES = 100        # squares of LIG lead in series (e.g. 100 mm x 1 mm) [DES]
C_DL = 4e-3               # F/cm2 LIG areal capacitance, 1 M H2SO4 at 20 mV/s (Lin 2014) [PUB, other electrolyte]
DRY_MIN = 1e6             # ohm, lowest expected dry reading (humid dressing) - TO BE MEASURED in E3 [EST]


def best_fsr(v):
    return min((f for f in FSR if f >= abs(v) * 1.05), default=FSR[0])


def rx_from_v(v, phase):
    return RREF * (VDD / v - 1) if phase > 0 else RREF * v / (VDD - v)


def v_from_rx(rx, phase):
    return VDD * RREF / (RREF + rx) if phase > 0 else VDD * rx / (RREF + rx)


def resolution(rx, phase):
    """Relative change in Rx corresponding to 1 LSB at the auto-ranged PGA."""
    v = v_from_rx(rx, phase)
    lsb = best_fsr(v) / 32768
    v2 = v + (lsb if phase > 0 else lsb)
    return abs(rx_from_v(min(max(v2, 1e-9), VDD - 1e-9), phase) - rx) / rx


def main():
    rows = []
    rx_list = [10 ** (k / 10) for k in range(20, 81)]           # 100 ohm .. 100 Mohm
    for rx in rx_list:
        rp, rn = resolution(rx, +1), resolution(rx, -1)
        rows.append((rx, rp, rn, min(rp, rn)))

    r_zone = [GAP / (k * LEN * t) for k in KAPPA_EFF for t in T_WET]
    r_lead = [rs * LEAD_SQUARES for rs in RS]
    wet_min, wet_max = min(r_zone) + 2 * RP + r_lead[0], max(r_zone) + 2 * RP + r_lead[1]
    thr = math.sqrt(wet_max * DRY_MIN)
    i_max = VDD / (RREF + wet_min)
    q = i_max * T_PHASE
    dv_dl = q / (C_DL * AREA_CM2)
    load_err = RREF / ADC_ZIN
    budget = math.sqrt(RREF_TOL ** 2 + GAIN_ERR ** 2 + load_err ** 2)

    fig, ax = plt.subplots(figsize=(7, 4))
    ax.loglog([r[0] for r in rows], [100 * r[1] for r in rows], label="phase + (1 LSB)")
    ax.loglog([r[0] for r in rows], [100 * r[2] for r in rows], label="phase − (1 LSB)")
    ax.axvspan(wet_min, wet_max, color="tab:blue", alpha=0.12, label="expected wet (calc)")
    ax.axvspan(DRY_MIN, 1e8, color="tab:orange", alpha=0.12, label="expected dry (est.)")
    ax.axvline(1e5, color="k", ls="--", lw=1, label="alert threshold 100 kΩ")
    ax.set_xlabel("Rx = zone + leads + 2 Rp (Ω)"); ax.set_ylabel("resolution per ADC LSB (%)")
    ax.set_title("ADS1115 + 100 kΩ divider: measurable range"); ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=7.5); fig.tight_layout(); fig.savefig(HERE / "calc_readout.png", dpi=150)

    def at(r):
        return min(rows, key=lambda x: abs(math.log10(x[0] / r)))

    lines = [
        "# Readout calculations (generated by calc_readout.py, 2026-10-14)",
        "",
        "Labels: [PUB] published · [DS] datasheet (verify) · [EST] estimate · [DES] design choice. **No measured data yet.**",
        "",
        "| Quantity | Value | Basis |",
        "|---|---|---|",
        f"| Solution A bulk conductivity | {KAPPA_SOLA:.2f} S/m | [EST] from molar conductivity of NaCl at 0.142 M + CaCl2 |",
        f"| Wet zone resistance (gap {GAP*1e3:.1f} mm, length {LEN*1e3:.0f} mm) | {min(r_zone):.0f}–{max(r_zone):.0f} Ω | [EST] R = g/(κ_eff·L·t), κ_eff {KAPPA_EFF[0]}–{KAPPA_EFF[1]} S/m, t {T_WET[0]*1e3:.1f}–{T_WET[1]*1e3:.1f} mm |",
        f"| LIG lead resistance ({LEAD_SQUARES} squares) | {r_lead[0]/1e3:.1f}–{r_lead[1]/1e3:.1f} kΩ | Rs {RS[0]:.0f}–{RS[1]:.0f} Ω/sq [PUB/EST] |",
        f"| Total wet reading Rx | {wet_min/1e3:.1f}–{wet_max/1e3:.1f} kΩ | sum incl. 2 × {RP/1e3:.0f} kΩ protection |",
        f"| Dry reading (lowest expected) | ≥ {DRY_MIN/1e6:.0f} MΩ | [EST], **must be measured** on the real dressing (E3 baseline) |",
        f"| Geometric-mean threshold | {thr/1e3:.0f} kΩ → use 100 kΩ alert, 300 kΩ release (hysteresis) | [DES] |",
        f"| Margin wet → threshold / threshold → dry | {1e5/wet_max:.1f}× / {DRY_MIN/1e5:.0f}× | [EST] |",
        f"| Resolution at 1 kΩ / 100 kΩ / 10 MΩ (best phase) | {100*at(1e3)[3]:.3f} % / {100*at(1e5)[3]:.3f} % / {100*at(1e7)[3]:.2f} % per LSB | [DS] ADS1115 auto-ranged |",
        f"| Systematic error budget (Rref, gain, ADC loading) | ±{100*budget:.1f} % | [DS]/[DES]; ADC loading {100*load_err:.1f} % is calibrated out with the on-board 100 kΩ check resistor |",
        f"| Max excitation current | {i_max*1e6:.0f} µA | [DES] Vdd / (Rref + Rx_min); bench only |",
        f"| Charge per {T_PHASE*1e3:.0f} ms phase | {q*1e6:.2f} µC | [DES] |",
        f"| Double-layer voltage swing per phase | {dv_dl*1e3:.2f} mV (×100 margin → {dv_dl*100:.2f} V) | [PUB] C ≈ 4 mF/cm² (Lin 2014, acid electrolyte) on {AREA_CM2:.2f} cm² |",
        "",
        "## Conclusions",
        "",
        f"1. **Wet vs dry is easy to tell apart.** Expected wet readings ({wet_min/1e3:.1f}–{wet_max/1e3:.0f} kΩ) and dry readings (≥ 1 MΩ) differ by more than 10×. A 100 kΩ threshold leaves margin on both sides **if** the real dry baseline is ≥ 1 MΩ.",
        "2. **The ADS1115 is more than adequate.** Resolution is better than 0.1 % per LSB from 1 kΩ to 1 MΩ. The ESP32-C3's internal ADC would also do for a binary threshold; the ADS1115 is chosen for logged, quantitative data (E3).",
        f"3. **No electrolysis expected.** Bipolar pulses move the LIG double layer by about {dv_dl*1e3:.1f} mV. Even with 100× less capacitance than the published value, that stays below the 1.23 V needed to split water.",
        "4. **Leads matter when wet.** Lead resistance (up to about 10 kΩ) is comparable to the wet zone itself. Treat the measurement as *wet/dry per zone* plus a trend, not as an absolute conductivity.",
        "",
        "![range](calc_readout.png)",
    ]
    (HERE / "calc_readout_report.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[4:20]))


if __name__ == "__main__":
    main()

"""
Sensor-concept decision matrix (scores are engineering judgement, 1 = poor, 5 = good; for cost/complexity/
burden criteria 5 = cheaper/simpler). Weights reflect OUR constraints: 11 days, one CO2 laser with an
unverified process window, multimeter-level metrology, bench-only validation.
Writes decision_matrix.md. Re-score after E2 and E4 data exist.
"""
from pathlib import Path

CRITERIA = [  # (name, weight, why it matters here)
    ("Signal contrast wet vs dry", 3, "must exceed process variation of LIG and leads"),
    ("Discrimination (front vs condensation, leak, handling, failure)", 3, "false alerts erode trust"),
    ("Repeatability given unknown LIG batch variation", 3, "our biggest unknown is Rs spread"),
    ("Calibration burden", 2, "nurse workflow cannot include calibration"),
    ("Geometry feasible with ~0.3 mm laser lines", 2, "unmeasured line growth"),
    ("Fluid compatibility (fouling, electrochemistry)", 2, "saline contact on electrodes"),
    ("Electronics complexity", 2, "11-day bench build"),
    ("Fabrication difficulty (layers, registration)", 2, "encapsulation windows must align"),
    ("Unit cost", 2, "disposable"),
    ("Disposable waste", 1, "material thrown away per change"),
    ("User workflow", 2, "placement on the dressing"),
    ("Safety", 2, "current through fluid; materials"),
    ("Validation burden", 2, "tests we can actually run"),
]

CONCEPTS = {
    "S1 Single-zone strip at the change line": [5, 2, 4, 4, 5, 4, 5, 5, 5, 5, 4, 5, 4],
    "S2 Two-zone strip: centre C + change line A": [5, 4, 4, 4, 4, 4, 5, 4, 5, 5, 4, 5, 4],
    "S3 Four-zone front strip: C, M, A, E": [5, 4, 4, 4, 3, 4, 4, 3, 4, 4, 4, 5, 3],
    "S4 Continuous resistive front locator (1 line + collector)": [3, 3, 2, 2, 4, 3, 4, 4, 5, 5, 4, 5, 2],
    "S5 Capacitive sealed electrodes (no fluid contact)": [3, 3, 3, 3, 4, 5, 2, 3, 4, 4, 4, 5, 3],
}
NOTES = {
    "S1 Single-zone strip at the change line": "Simplest. Cannot tell a genuine front from a drip, an external leak or handling at the window.",
    "S2 Two-zone strip: centre C + change line A": "Adds an ORDER check: a real front wets C before A. A-before-C flags CHECK (leak, handling, misplacement). Needs only 2 sense lanes.",
    "S3 Four-zone front strip: C, M, A, E": "Early warning (M) and a leak zone (E), but 4 lanes, tighter routing and more registration-critical windows; unproven benefit.",
    "S4 Continuous resistive front locator (1 line + collector)": "Elegant (3 contacts), but the reading depends directly on LIG Rs uniformity, our least-known property.",
    "S5 Capacitive sealed electrodes (no fluid contact)": "Best fluid compatibility; needs a capacitance front end (the ESP32-C3 has no touch peripheral) and lamination.",
}


def main():
    tot_w = sum(w for _, w, _ in CRITERIA)
    scores = {k: sum(s * w for s, (_, w, _) in zip(v, CRITERIA)) / tot_w for k, v in CONCEPTS.items()}
    ranked = sorted(scores.items(), key=lambda kv: -kv[1])
    head = "| Criterion (weight) | " + " | ".join(k.split(" ")[0] for k in CONCEPTS) + " |"
    lines = ["# Sensor decision matrix (generated by decision_matrix.py)", "",
             "Scores 1–5 (5 = better / simpler / cheaper). Engineering judgement, to be re-scored after E2 and E4.", "",
             head, "|" + "---|" * (len(CONCEPTS) + 1)]
    for i, (name, w, _) in enumerate(CRITERIA):
        lines.append(f"| {name} ({w}) | " + " | ".join(str(v[i]) for v in CONCEPTS.values()) + " |")
    lines.append("| **Weighted score / 5** | " + " | ".join(f"**{scores[k]:.2f}**" for k in CONCEPTS) + " |")
    lines += ["", "## Ranking", ""]
    lines += [f"{i + 1}. {k}: **{v:.2f}**. {NOTES[k]}" for i, (k, v) in enumerate(ranked)]
    (Path(__file__).with_name("decision_matrix.md")).write_text("\n".join(lines), encoding="utf-8")
    for k, v in ranked:
        print(f"{v:.2f}  {k}")


if __name__ == "__main__":
    main()
